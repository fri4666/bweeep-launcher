import assert from 'node:assert/strict';
import { createHash, createPublicKey, verify } from 'node:crypto';
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
const [filename, version, githubSha, publicKeyFile, output] = process.argv.slice(2);
assert.match(githubSha, /^[a-f0-9]{64}$/);
const keyBytes = Buffer.from((await fsp.readFile(publicKeyFile, 'utf8')).replace(/\r\n/g, '\n'));
assert.equal(createHash('sha256').update(keyBytes).digest('hex'), 'fd477072e06776065e36819e67ddac5ef43381c54a09a61e599a81eeb5262d38', 'Verification key changed');
const response = await fetch(`https://tmwvrglzjfzauuygofpp.supabase.co/storage/v1/object/public/bweeep-launcher-updates/installers/${version}/x64.json`, { cache: 'no-store' });
assert.equal(response.status, 200);
const manifest = await response.json();
const { schema, arch, size, sha256, chunkSize, chunks, signature } = manifest;
assert.equal(schema, 1); assert.equal(manifest.version, version); assert.equal(arch, 'x64');
assert.ok(Number.isSafeInteger(size) && size > 0);
assert.equal(chunkSize, 5 * 1024 * 1024); assert.equal(chunks, Math.ceil(size / chunkSize));
assert.equal(sha256, githubSha, 'GitHub installer digest differs from signed installer archive');
const payload = { schema, version, arch, size, sha256, chunkSize, chunks };
assert.equal(verify(null, Buffer.from(JSON.stringify(payload)), createPublicKey(keyBytes), Buffer.from(signature, 'base64')), true, 'Archived installer signature invalid');
assert.equal((await fsp.stat(filename)).size, size);
const hash = createHash('sha256');
for await (const chunk of fs.createReadStream(filename)) hash.update(chunk);
assert.equal(hash.digest('hex'), sha256);
await fsp.writeFile(path.join(output, 'installer-verification.json'), JSON.stringify({ version, size, sha256, signatureVerified: true, githubAssetDigestAgrees: true, verificationKeySha256: createHash('sha256').update(keyBytes).digest('hex') }, null, 2));
console.log(`signed-installer=${version}`);
