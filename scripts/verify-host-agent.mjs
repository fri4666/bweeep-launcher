import assert from "node:assert/strict";
import {HostAgent} from "../infra/hosting/host-agent.mjs";
let clock=100000;
const state=(node="vps")=>({policy:{primaryNode:"vps",automatic:false,failureSeconds:90,syncMinutes:5,maxSnapshotMinutes:10,allowRecovery:false},revision:1,activeNode:node,epoch:2,leaseUntil:new Date(clock+60000).toISOString(),requestedNode:null,nodes:[]});
const config={node:"vps",cluster:"test"};
let events=[],reply={granted:true,restoreRequired:false,serverNow:new Date(clock).toISOString(),state:state()},throws=false;
const io={session:"session",now:()=>clock,write:async s=>events.push(["write",s.restoreRequired]),driver:async a=>events.push(["driver",a]),sync:async d=>events.push(["sync",d]),api:async(name)=>{events.push(["api",name]);if(throws)throw new Error("offline");return reply;}};
const agent=new HostAgent(config,io);
await agent.tick();await agent.transition;
assert.equal(agent.mode,"active");
assert.deepEqual(events.filter(x=>x[0]==="driver").map(x=>x[1]),["activate","permit"]);
clock+=13001;throws=true;await agent.tick();
assert.equal(agent.mode,"fenced");
assert.equal(events.at(-1)[1],"fence");
throws=false;reply={granted:false,serverNow:new Date(clock).toISOString(),state:state("pc")};
events=[];await agent.tick();
assert.deepEqual(events.filter(x=>x[0]==="driver").map(x=>x[1]),["proxy","permit"]);
assert.equal(agent.mode,"standby");
let finish;
const delayed=new HostAgent(config,{...io,driver:async a=>{events.push(["driver",a]);if(a==="activate")await new Promise(r=>finish=r);}});
events=[];reply={granted:true,restoreRequired:true,serverNow:new Date(clock).toISOString(),state:state()};
await delayed.tick();await new Promise(r=>setImmediate(r));
assert.equal(delayed.mode,"activating");
clock+=13001;await delayed.watchdog();finish();await delayed.transition;
assert.equal(delayed.mode,"fenced");
assert.ok(!events.some(x=>x[0]==="driver"&&x[1]==="permit"),"Late activation reopened fenced ports");
const released=new HostAgent(config,{...io,api:async name=>{events.push(["api",name]);return {...state(),requestedNode:"pc"};}});
released.mode="released";events=[];await released.tick();
assert.ok(events.every(x=>x[0]!=="api"||x[1]==="launcher_host_state"),"Released owner renewed its old lease");
events=[];
let handoffState={...state(),requestedNode:"pc",nodes:[{node:"pc",snapshotSource:"vps",snapshotEpoch:2,snapshotAt:new Date(clock+1).toISOString()}]};
const handoff=new HostAgent(config,{...io,api:async name=>{
 events.push(["api",name]);
 if(name==="launcher_host_poll")return {granted:true,serverNow:new Date(clock).toISOString(),state:handoffState};
 if(name==="launcher_host_release")return true;
 return handoffState;
}});
handoff.mode="active";handoff.lastGrant=clock;
await handoff.tick();await handoff.transition;
assert.equal(handoff.mode,"released");
const fenceAt=events.findIndex(x=>x[0]==="driver"&&x[1]==="fence"),releaseAt=events.findIndex(x=>x[0]==="api"&&x[1]==="launcher_host_release");
assert.ok(fenceAt>=0&&releaseAt>fenceAt,"Handoff released before fencing");
console.log("Host agent: exclusive activation, outage fencing, proxy role, late completion, released-owner and handoff ordering PASS");
